'use client';

import { useState } from 'react';
import { createStoreAction } from '@/app/actions/superadmin-actions';

interface CreateStoreDialogProps {
  isOpen: boolean;
  onClose: () => void;
  onStoreCreated: () => void;
}

const PRESET_COLORS = [
  { name: 'Rose', hex: '#E11D48' },
  { name: 'Amber', hex: '#D97706' },
  { name: 'Emerald', hex: '#059669' },
  { name: 'Blue', hex: '#2563EB' },
  { name: 'Purple', hex: '#7C3AED' },
  { name: 'Dark', hex: '#171717' },
];

function slugify(text: string): string {
  return text
    .toString()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function CreateStoreDialog({ isOpen, onClose, onStoreCreated }: CreateStoreDialogProps) {
  const [name, setName] = useState('');
  const [slug, setSlug] = useState('');
  const [isSlugManual, setIsSlugManual] = useState(false);
  const [phoneWhatsapp, setPhoneWhatsapp] = useState('');
  const [yapeNumber, setYapeNumber] = useState('');
  const [ownerEmail, setOwnerEmail] = useState('');
  const [ownerPassword, setOwnerPassword] = useState('');
  const [accentColor, setAccentColor] = useState('#E11D48');
  const [isPasswordAutogenerated, setIsPasswordAutogenerated] = useState(false);

  const [isSubmitting, setIsSubmitting] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [createdSummary, setCreatedSummary] = useState<{
    slug: string;
    email: string;
    password?: string;
  } | null>(null);
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  function handleNameChange(e: React.ChangeEvent<HTMLInputElement>) {
    const val = e.target.value;
    setName(val);
    if (!isSlugManual) {
      setSlug(slugify(val));
    }
  }

  function handleGeneratePassword() {
    const chars = 'abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789!@#$%&*';
    const bytes = new Uint8Array(12);
    crypto.getRandomValues(bytes);
    const generated = Array.from(bytes, (b) => chars[b % chars.length]).join('');
    setOwnerPassword(generated);
    setIsPasswordAutogenerated(true);
  }

  async function handleCopyCredentials() {
    if (!createdSummary) return;
    const text = `🎉 ¡Hola! Ya está listo tu catálogo digital en Menuki.\n\n🌐 Tu Catálogo Público: https://menuki-phi.vercel.app/${createdSummary.slug}\n🔑 Panel de Control: https://menuki-phi.vercel.app/${createdSummary.slug}/admin\n\n👤 Correo de acceso: ${createdSummary.email}${createdSummary.password ? `\n🔐 Contraseña: ${createdSummary.password}` : ''}\n\n¡Ingresa a tu panel para agregar tus productos y fotos!`;
    await navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  }

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    setErrorMessage(null);
    setIsSubmitting(true);

    try {
      const res = await createStoreAction({
        name,
        slug,
        ownerEmail,
        ownerPassword,
        phoneWhatsapp,
        yapeNumber: yapeNumber || '',
        accentColor,
        isPasswordAutogenerated,
      });

      if (!res.ok) {
        setErrorMessage(res.error || 'No se pudo crear el local.');
      } else {
        setCreatedSummary({
          slug: res.data?.slug || slug,
          email: ownerEmail,
          password: res.generatedPassword,
        });
        onStoreCreated();
      }
    } catch {
      setErrorMessage('Error de red al procesar el alta del local.');
    } finally {
      setIsSubmitting(false);
    }
  }

  function handleClose() {
    setName('');
    setSlug('');
    setIsSlugManual(false);
    setPhoneWhatsapp('');
    setYapeNumber('');
    setOwnerEmail('');
    setOwnerPassword('');
    setIsPasswordAutogenerated(false);
    setErrorMessage(null);
    setCreatedSummary(null);
    onClose();
  }

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4 backdrop-blur-sm overflow-y-auto">
      <div className="my-8 w-full max-w-lg rounded-3xl border border-neutral-200 bg-white p-6 shadow-2xl">
        <div className="flex items-center justify-between border-b border-neutral-100 pb-3">
          <div>
            <h2 className="text-base font-bold text-neutral-900">Dar de Alta un Nuevo Local</h2>
            <p className="text-xs text-neutral-500">
              Registra el comercio y genera sus accesos al instante.
            </p>
          </div>
          <button
            onClick={handleClose}
            className="rounded-lg p-1.5 text-neutral-400 hover:bg-neutral-100 hover:text-neutral-700"
          >
            ✕
          </button>
        </div>

        {createdSummary ? (
          <div className="mt-5 space-y-4">
            <div className="rounded-2xl border border-emerald-200 bg-emerald-50 p-5 text-emerald-900">
              <div className="flex items-center gap-2">
                <span className="flex h-6 w-6 items-center justify-center rounded-full bg-emerald-600 text-xs font-bold text-white">
                  ✓
                </span>
                <h3 className="font-bold text-sm">¡Local dado de alta con éxito!</h3>
              </div>

              <div className="mt-4 space-y-2 rounded-xl bg-white/90 p-4 font-mono text-xs text-neutral-800">
                <p>
                  <strong>Slug:</strong> /{createdSummary.slug}
                </p>
                <p>
                  <strong>Email Dueño:</strong> {createdSummary.email}
                </p>
                {createdSummary.password && (
                  <p className="rounded bg-amber-50 p-1.5 font-bold text-amber-900">
                    Contraseña generada: {createdSummary.password}
                  </p>
                )}
              </div>

              <button
                type="button"
                onClick={handleCopyCredentials}
                className="mt-4 w-full rounded-xl bg-emerald-600 py-2.5 text-xs font-bold text-white transition hover:bg-emerald-700"
              >
                {copied ? '¡Credenciales copiadas al portapapeles!' : '📋 Copiar mensaje para WhatsApp'}
              </button>
            </div>

            <button
              type="button"
              onClick={handleClose}
              className="w-full rounded-xl bg-neutral-900 py-2.5 text-xs font-bold text-white transition hover:bg-neutral-800"
            >
              Listo, volver a la lista
            </button>
          </div>
        ) : (
          <form onSubmit={handleSubmit} className="mt-4 space-y-3.5">
            {errorMessage && (
              <div className="rounded-xl bg-rose-50 p-3 text-xs text-rose-700">
                {errorMessage}
              </div>
            )}

            <div>
              <label className="block text-xs font-semibold text-neutral-700">
                Nombre del Negocio *
              </label>
              <input
                type="text"
                required
                value={name}
                onChange={handleNameChange}
                placeholder="Ej. Sanguchería El Cholo"
                className="mt-1 w-full rounded-xl border border-neutral-300 px-3 py-2 text-xs text-neutral-900 focus:border-neutral-900 focus:outline-none focus:ring-1 focus:ring-neutral-900"
              />
            </div>

            <div>
              <label className="block text-xs font-semibold text-neutral-700">
                Slug (URL del local) *
              </label>
              <div className="mt-1 flex items-center rounded-xl border border-neutral-300 bg-neutral-50 px-3 py-1.5 focus-within:border-neutral-900 focus-within:ring-1 focus-within:ring-neutral-900">
                <span className="text-xs text-neutral-400">menuki.pe/</span>
                <input
                  type="text"
                  required
                  value={slug}
                  onChange={(e) => {
                    setIsSlugManual(true);
                    setSlug(e.target.value.toLowerCase().trim());
                  }}
                  placeholder="sangucheria-el-cholo"
                  className="w-full bg-transparent px-1 font-mono text-xs text-neutral-900 focus:outline-none"
                />
              </div>
            </div>

            <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
              <div>
                <label className="block text-xs font-semibold text-neutral-700">
                  WhatsApp Pedidos (519XXXXXXXX) *
                </label>
                <input
                  type="text"
                  required
                  value={phoneWhatsapp}
                  onChange={(e) => setPhoneWhatsapp(e.target.value.trim())}
                  placeholder="51987654321"
                  maxLength={11}
                  className="mt-1 w-full rounded-xl border border-neutral-300 px-3 py-2 font-mono text-xs text-neutral-900 focus:border-neutral-900 focus:outline-none focus:ring-1 focus:ring-neutral-900"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-neutral-700">
                  Número Yape / Plin (9 dígitos)
                </label>
                <input
                  type="text"
                  value={yapeNumber}
                  onChange={(e) => setYapeNumber(e.target.value.trim())}
                  placeholder="987654321"
                  maxLength={9}
                  className="mt-1 w-full rounded-xl border border-neutral-300 px-3 py-2 font-mono text-xs text-neutral-900 focus:border-neutral-900 focus:outline-none focus:ring-1 focus:ring-neutral-900"
                />
              </div>
            </div>

            <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
              <div>
                <label className="block text-xs font-semibold text-neutral-700">
                  Email del Dueño *
                </label>
                <input
                  type="email"
                  required
                  value={ownerEmail}
                  onChange={(e) => setOwnerEmail(e.target.value.trim().toLowerCase())}
                  placeholder="cliente@negocio.pe"
                  className="mt-1 w-full rounded-xl border border-neutral-300 px-3 py-2 text-xs text-neutral-900 focus:border-neutral-900 focus:outline-none focus:ring-1 focus:ring-neutral-900"
                />
              </div>

              <div>
                <div className="flex items-center justify-between">
                  <label className="block text-xs font-semibold text-neutral-700">
                    Contraseña Inicial *
                  </label>
                  <button
                    type="button"
                    onClick={handleGeneratePassword}
                    className="text-[11px] font-semibold text-neutral-600 underline hover:text-neutral-900"
                  >
                    Generar segura
                  </button>
                </div>
                <input
                  type="text"
                  required
                  minLength={8}
                  value={ownerPassword}
                  onChange={(e) => {
                    setOwnerPassword(e.target.value);
                    setIsPasswordAutogenerated(false);
                  }}
                  placeholder="Mínimo 8 caracteres"
                  className="mt-1 w-full rounded-xl border border-neutral-300 px-3 py-2 font-mono text-xs text-neutral-900 focus:border-neutral-900 focus:outline-none focus:ring-1 focus:ring-neutral-900"
                />
              </div>
            </div>

            <div>
              <label className="block text-xs font-semibold text-neutral-700">
                Color de Marca
              </label>
              <div className="mt-1.5 flex items-center gap-2">
                {PRESET_COLORS.map((c) => (
                  <button
                    key={c.hex}
                    type="button"
                    onClick={() => setAccentColor(c.hex)}
                    style={{ backgroundColor: c.hex }}
                    className={`h-7 w-7 rounded-full border-2 transition ${
                      accentColor.toLowerCase() === c.hex.toLowerCase()
                        ? 'border-neutral-900 scale-110 shadow-md'
                        : 'border-white opacity-80 hover:opacity-100'
                    }`}
                    title={c.name}
                  />
                ))}
                <input
                  type="color"
                  value={accentColor}
                  onChange={(e) => setAccentColor(e.target.value)}
                  className="h-7 w-7 cursor-pointer rounded-full border-0 bg-transparent p-0"
                />
              </div>
            </div>

            <div className="flex justify-end gap-2 pt-3">
              <button
                type="button"
                onClick={handleClose}
                className="rounded-xl border border-neutral-200 px-4 py-2 text-xs font-semibold text-neutral-600 hover:bg-neutral-50"
              >
                Cancelar
              </button>
              <button
                type="submit"
                disabled={isSubmitting}
                className="rounded-xl bg-neutral-900 px-5 py-2 text-xs font-bold text-white transition hover:bg-neutral-800 disabled:opacity-50"
              >
                {isSubmitting ? 'Creando local...' : 'Crear Local'}
              </button>
            </div>
          </form>
        )}
      </div>
    </div>
  );
}
