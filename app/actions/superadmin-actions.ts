'use server';

import { revalidatePath, revalidateTag } from 'next/cache';
import { z } from 'zod';
import { createAdminClient } from '@/lib/supabase/admin';
import { requireSuperadmin } from '@/lib/auth/require-superadmin';
import { rethrowIfRedirect } from '@/lib/auth/rethrow-if-redirect';

// -----------------------------------------------------------------------------
// AUDIT LOGGING HELPER (Requirement 8: Structured audit log without passwords)
// -----------------------------------------------------------------------------
type AuditAction = 'CREATE_STORE' | 'TOGGLE_STORE_ACTIVE' | 'RESET_OWNER_PASSWORD';

function logAudit(entry: {
  action: AuditAction;
  superadminEmail: string;
  storeId?: string | null;
  targetUserId?: string | null;
  details?: Record<string, unknown>;
}) {
  const auditPayload = {
    timestamp: new Date().toISOString(),
    superadminEmail: entry.superadminEmail,
    action: entry.action,
    storeId: entry.storeId ?? null,
    targetUserId: entry.targetUserId ?? null,
    details: entry.details ?? {},
  };
  // Structured log for cloud monitoring / stdout
  console.log('[AUDIT_LOG]', JSON.stringify(auditPayload));
}

// -----------------------------------------------------------------------------
// SCHEMAS (Requirement 6: Zod validation)
// -----------------------------------------------------------------------------
const createStoreSchema = z.object({
  name: z
    .string()
    .trim()
    .min(2, 'El nombre debe tener al menos 2 caracteres')
    .max(80, 'El nombre no puede superar 80 caracteres'),
  slug: z
    .string()
    .trim()
    .toLowerCase()
    .regex(
      /^[a-z0-9]+(?:-[a-z0-9]+)*$/,
      'El slug debe contener únicamente letras minúsculas, números y guiones'
    ),
  ownerEmail: z.string().trim().toLowerCase().email('Correo electrónico inválido'),
  ownerPassword: z.string().min(8, 'La contraseña debe tener al menos 8 caracteres'),
  phoneWhatsapp: z
    .string()
    .trim()
    .regex(/^519\d{8}$/, 'El WhatsApp debe tener 11 dígitos iniciando con 519 (ej. 51987654321)'),
  yapeNumber: z
    .string()
    .trim()
    .regex(/^9\d{8}$/, 'El número de Yape/Plin debe tener 9 dígitos iniciando con 9')
    .optional()
    .or(z.literal('')),
  accentColor: z
    .string()
    .trim()
    .regex(/^#[0-9A-Fa-f]{6}$/, 'Color hexadecimal inválido')
    .optional(),
  isPasswordAutogenerated: z.boolean().optional(),
});

const resetPasswordSchema = z.object({
  userId: z.string().uuid('ID de usuario inválido'),
  newPassword: z.string().min(8, 'La nueva contraseña debe tener al menos 8 caracteres'),
});

const toggleStoreActiveSchema = z.object({
  storeId: z.string().uuid('ID de tienda inválido'),
  isActive: z.boolean(),
});

// -----------------------------------------------------------------------------
// TYPES
// -----------------------------------------------------------------------------
export interface SuperadminStoreItem {
  id: string;
  slug: string;
  name: string;
  phoneWhatsapp: string | null;
  yapeNumber: string | null;
  accentColor: string;
  isActive: boolean;
  isOpenManual: boolean;
  createdAt: string;
  ownerEmail: string | null;
  ownerUserId: string | null;
}

export interface SuperadminActionResponse<T = unknown> {
  ok: boolean;
  error?: string;
  data?: T;
  generatedPassword?: string;
}

// -----------------------------------------------------------------------------
// 1. GET ALL STORES (Requirement 9: Single query + user map, limit 200, TODO page)
// -----------------------------------------------------------------------------
export async function getAllStoresAction(): Promise<
  SuperadminActionResponse<{ stores: SuperadminStoreItem[] }>
> {
  try {
    const { user: superadmin } = await requireSuperadmin();
    const supabaseAdmin = createAdminClient();

    // Single query to stores with store_members
    // TODO: Implement cursor/offset pagination once stores exceed 200
    const { data: storesData, error: storesError } = await supabaseAdmin
      .from('stores')
      .select('id, slug, name, phone_whatsapp, yape_number, accent_color, is_active, is_open_manual, created_at, store_members(user_id, role)')
      .order('created_at', { ascending: false })
      .limit(200);

    if (storesError) {
      return { ok: false, error: 'No se pudieron obtener los locales registrados.' };
    }

    // Single call to list auth users and map in memory
    const { data: usersData, error: usersError } = await supabaseAdmin.auth.admin.listUsers({
      perPage: 1000,
    });

    if (usersError) {
      return { ok: false, error: 'No se pudieron obtener los datos de usuarios del sistema.' };
    }

    const emailByUserId = new Map<string, string>();
    for (const u of usersData.users) {
      if (u.email) {
        emailByUserId.set(u.id, u.email);
      }
    }

    const result: SuperadminStoreItem[] = (storesData ?? []).map((s) => {
      // Find owner member
      const members = (s.store_members ?? []) as Array<{ user_id: string; role: string }>;
      const ownerMember = members.find((m) => m.role === 'owner') || members[0];
      const ownerUserId = ownerMember?.user_id ?? null;
      const ownerEmail = ownerUserId ? emailByUserId.get(ownerUserId) ?? null : null;

      return {
        id: s.id,
        slug: s.slug,
        name: s.name,
        phoneWhatsapp: s.phone_whatsapp,
        yapeNumber: s.yape_number,
        accentColor: s.accent_color,
        isActive: s.is_active,
        isOpenManual: s.is_open_manual,
        createdAt: s.created_at,
        ownerEmail,
        ownerUserId,
      };
    });

    return { ok: true, data: { stores: result } };
  } catch (err) {
    rethrowIfRedirect(err);
    return { ok: false, error: 'Ocurrió un error inesperado al consultar los locales.' };
  }
}

// -----------------------------------------------------------------------------
// 2. TOGGLE STORE ACTIVE STATUS (Requirement 3, 4, 6, 8)
// -----------------------------------------------------------------------------
export async function toggleStoreActiveAction(
  storeId: string,
  isActive: boolean
): Promise<SuperadminActionResponse> {
  try {
    const { user: superadmin } = await requireSuperadmin();

    const parsed = toggleStoreActiveSchema.safeParse({ storeId, isActive });
    if (!parsed.success) {
      return { ok: false, error: parsed.error.issues[0]?.message ?? 'Datos inválidos' };
    }

    const supabaseAdmin = createAdminClient();

    // 1. Fetch store to obtain slug for cache invalidation
    const { data: store, error: findError } = await supabaseAdmin
      .from('stores')
      .select('id, slug')
      .eq('id', storeId)
      .maybeSingle();

    if (findError || !store) {
      return { ok: false, error: 'El local no fue encontrado.' };
    }

    // 2. Update is_active
    const { error: updateError } = await supabaseAdmin
      .from('stores')
      .update({ is_active: isActive })
      .eq('id', storeId);

    if (updateError) {
      return { ok: false, error: 'No se pudo actualizar el estado de membresía del local.' };
    }

    // Audit log (zero passwords)
    logAudit({
      action: 'TOGGLE_STORE_ACTIVE',
      superadminEmail: superadmin.email,
      storeId: store.id,
      details: { newIsActive: isActive, slug: store.slug },
    });

    // Invalidate ISR cache and Next.js tags
    revalidatePath(`/${store.slug}`);
    revalidatePath('/superadmin');
    revalidateTag('catalog');

    return { ok: true };
  } catch (err) {
    rethrowIfRedirect(err);
    return { ok: false, error: 'Error al cambiar el estado del local.' };
  }
}

// -----------------------------------------------------------------------------
// 3. CREATE STORE WITH MANUAL TRANSACTION ROLLBACK (Requirements 5, 6, 7, 8)
// -----------------------------------------------------------------------------
export async function createStoreAction(
  input: z.infer<typeof createStoreSchema>
): Promise<SuperadminActionResponse<{ storeId: string; slug: string }>> {
  let createdAuthUserId: string | null = null;
  let createdStoreId: string | null = null;
  let isNewUserCreated = false;

  try {
    const { user: superadmin } = await requireSuperadmin();

    // 1. Zod Validation
    const parsed = createStoreSchema.safeParse(input);
    if (!parsed.success) {
      return { ok: false, error: parsed.error.issues[0]?.message ?? 'Verifica los datos ingresados' };
    }

    const {
      name,
      slug,
      ownerEmail,
      ownerPassword,
      phoneWhatsapp,
      yapeNumber,
      accentColor,
      isPasswordAutogenerated,
    } = parsed.data;

    const supabaseAdmin = createAdminClient();

    // 2. Check if slug already exists
    const { data: existingSlug, error: slugCheckError } = await supabaseAdmin
      .from('stores')
      .select('id')
      .eq('slug', slug)
      .maybeSingle();

    if (slugCheckError) {
      return { ok: false, error: 'Error al verificar disponibilidad del slug.' };
    }

    if (existingSlug) {
      return { ok: false, error: `El slug "${slug}" ya se encuentra registrado. Elige otro.` };
    }

    // 3. User Resolution: Check if ownerEmail already exists in Auth
    // Decision: If user exists, associate store to existing user; otherwise create new Auth user.
    const { data: existingUsersData } = await supabaseAdmin.auth.admin.listUsers({
      perPage: 1000,
    });

    const matchedUser = existingUsersData?.users.find(
      (u) => u.email?.trim().toLowerCase() === ownerEmail
    );

    if (matchedUser) {
      createdAuthUserId = matchedUser.id;
      isNewUserCreated = false;
    } else {
      const { data: newUserData, error: createUserError } =
        await supabaseAdmin.auth.admin.createUser({
          email: ownerEmail,
          password: ownerPassword,
          email_confirm: true,
        });

      if (createUserError || !newUserData.user) {
        return {
          ok: false,
          error: 'No se pudo crear la cuenta del dueño en el sistema de autenticación.',
        };
      }

      createdAuthUserId = newUserData.user.id;
      isNewUserCreated = true;
    }

    // 4. Insert into stores
    const { data: insertedStore, error: insertStoreError } = await supabaseAdmin
      .from('stores')
      .insert({
        slug,
        name,
        phone_whatsapp: phoneWhatsapp,
        yape_number: yapeNumber || null,
        accent_color: accentColor || '#E11D48',
        currency: 'PEN',
        is_active: true,
        is_open_manual: true,
      })
      .select('id, slug')
      .single();

    if (insertStoreError || !insertedStore) {
      // Rollback newly created user if store insertion failed
      if (isNewUserCreated && createdAuthUserId) {
        await supabaseAdmin.auth.admin.deleteUser(createdAuthUserId);
      }
      return { ok: false, error: 'Error al registrar el local en la base de datos.' };
    }

    createdStoreId = insertedStore.id;

    // 5. Insert into store_members as 'owner'
    const { error: memberError } = await supabaseAdmin.from('store_members').insert({
      store_id: insertedStore.id,
      user_id: createdAuthUserId,
      role: 'owner',
    });

    if (memberError) {
      // Manual transaction rollback: delete store and delete created auth user
      await supabaseAdmin.from('stores').delete().eq('id', createdStoreId);
      if (isNewUserCreated && createdAuthUserId) {
        await supabaseAdmin.auth.admin.deleteUser(createdAuthUserId);
      }
      return { ok: false, error: 'Error al asignar la membresía del local.' };
    }

    // 6. Also ensure superadmin is linked as owner so RLS allows direct administration
    if (superadmin.id !== createdAuthUserId) {
      await supabaseAdmin.from('store_members').upsert(
        {
          store_id: insertedStore.id,
          user_id: superadmin.id,
          role: 'owner',
        },
        { onConflict: 'store_id,user_id' }
      );
    }

    // Audit log (never logs passwords)
    logAudit({
      action: 'CREATE_STORE',
      superadminEmail: superadmin.email,
      storeId: insertedStore.id,
      targetUserId: createdAuthUserId,
      details: { slug: insertedStore.slug, isNewUserCreated },
    });

    revalidatePath('/superadmin');
    revalidatePath(`/${insertedStore.slug}`);

    return {
      ok: true,
      data: { storeId: insertedStore.id, slug: insertedStore.slug },
      // Return password ONLY if autogenerated for one-time display in UI modal
      generatedPassword: isPasswordAutogenerated ? ownerPassword : undefined,
    };
  } catch (err) {
    // Safety rollback in case of uncaught exceptions
    if (createdStoreId) {
      try {
        const rollbackAdmin = createAdminClient();
        await rollbackAdmin.from('stores').delete().eq('id', createdStoreId);
      } catch {
        // best effort
      }
    }
    if (isNewUserCreated && createdAuthUserId) {
      try {
        const rollbackAdmin = createAdminClient();
        await rollbackAdmin.auth.admin.deleteUser(createdAuthUserId);
      } catch {
        // best effort
      }
    }

    rethrowIfRedirect(err);
    return { ok: false, error: 'Ocurrió un error inesperado al dar de alta el local.' };
  }
}

// -----------------------------------------------------------------------------
// 4. RESET OWNER PASSWORD (Requirements 6, 7, 8)
// -----------------------------------------------------------------------------
export async function resetOwnerPasswordAction(
  userId: string,
  newPassword: string
): Promise<SuperadminActionResponse> {
  try {
    const { user: superadmin } = await requireSuperadmin();

    const parsed = resetPasswordSchema.safeParse({ userId, newPassword });
    if (!parsed.success) {
      return { ok: false, error: parsed.error.issues[0]?.message ?? 'Contraseña inválida' };
    }

    const supabaseAdmin = createAdminClient();

    const { error: updateError } = await supabaseAdmin.auth.admin.updateUserById(userId, {
      password: newPassword,
    });

    if (updateError) {
      return { ok: false, error: 'No se pudo actualizar la contraseña del usuario.' };
    }

    logAudit({
      action: 'RESET_OWNER_PASSWORD',
      superadminEmail: superadmin.email,
      targetUserId: userId,
    });

    return { ok: true };
  } catch (err) {
    rethrowIfRedirect(err);
    return { ok: false, error: 'Error inesperado al restablecer la contraseña.' };
  }
}
